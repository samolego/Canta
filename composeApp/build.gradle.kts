    isCanBeConsumed = false
    isCanBeResolved = true
    attributes {
        attribute(Usage.USAGE_ATTRIBUTE, objects.named(Usage::class, "canta-adb-helper-apk"))
    }
}

dependencies {
    adbHelperApk(project(":helper"))
}

val prepareAdbHelper = tasks.register<PrepareAdbHelper>("prepareAdbHelper") {
    apkDirectory.from(adbHelperApk)
    minSdk.set(libs.versions.android.minSdk.get().toInt())
    resourcesDirectory.set(layout.buildDirectory.dir("generated/adbHelper/resources"))
    sourcesDirectory.set(layout.buildDirectory.dir("generated/adbHelper/kotlin"))
}

