/**
 * Copies the on-device ADB helper APK (built by `:helper`) into a Compose
 * resources directory and generates `AdbHelperArtifact` with its SHA-256, so
 * the desktop/web clients can tell whether the copy on a device is current,
 * and the lowest SDK it runs on.
 */
abstract class PrepareAdbHelper : DefaultTask() {
    @get:InputFiles
    abstract val apkDirectory: ConfigurableFileCollection

    @get:Input
    abstract val minSdk: Property<Int>

    @get:OutputDirectory
    abstract val resourcesDirectory: DirectoryProperty

    @get:OutputDirectory
    abstract val sourcesDirectory: DirectoryProperty

    @TaskAction
    fun prepare() {
        val apk = apkDirectory.asFileTree.matching { include("*.apk") }.singleFile
        val bytes = apk.readBytes()
        val sha256 = MessageDigest.getInstance("SHA-256").digest(bytes)
            .joinToString("") { "%02x".format(it) }

        resourcesDirectory.get().asFile.resolve("files").apply {
            deleteRecursively()
            mkdirs()
            resolve("canta-helper.apk").writeBytes(bytes)
        }
        sourcesDirectory.get().asFile.resolve("io/github/samolego/canta/core/adb").apply {
            deleteRecursively()
            mkdirs()
            resolve("AdbHelperArtifact.kt").writeText(
                """
                |// Generated by the prepareAdbHelper task. Do not edit.
                |package io.github.samolego.canta.core.adb
                |
                |internal object AdbHelperArtifact {
                |    /** Compose resource path of the bundled helper APK. */
                |    const val RESOURCE_PATH = "files/canta-helper.apk"
                |    const val SHA256 = "$sha256"
                |    /** Devices on older Android versions are refused. */
                |    const val MIN_SDK = ${minSdk.get()}
                |}
                |""".trimMargin()
            )
        }
    }
}

/** Generates `BuildInfo` with the app version from `gradle.properties`, for every target. */
@CacheableTask
abstract class GenerateBuildInfo : DefaultTask() {
    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val versionCode: Property<Int>

    @get:OutputDirectory
    abstract val sourcesDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        sourcesDirectory.get().asFile.resolve("io/github/samolego/canta").apply {
            deleteRecursively()
            mkdirs()
            resolve("BuildInfo.kt").writeText(
                """
                |// Generated by the generateBuildInfo task. Do not edit.
                |package io.github.samolego.canta
                |
                |object BuildInfo {
                |    const val VERSION_NAME = "${versionName.get()}"
                |    const val VERSION_CODE = ${versionCode.get()}
                |}
                |""".trimMargin()
            )
        }
    }
}

val generateBuildInfo = tasks.register<GenerateBuildInfo>("generateBuildInfo") {
    versionName.set(providers.gradleProperty("version_name"))
    versionCode.set(providers.gradleProperty("version_code").map(String::toInt))
    sourcesDirectory.set(layout.buildDirectory.dir("generated/buildInfo/kotlin"))
}

